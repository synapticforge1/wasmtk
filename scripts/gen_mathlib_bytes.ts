// Reads src/wasm/mathlib.wasm and writes src/wasm/mathlib_bytes.ts as a
// Uint8Array constant. Run this after recompiling mathlib.wat.
//
// Usage: bun scripts/gen_mathlib_bytes.ts

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = join(scriptDir, "..");
const wasmPath = join(root, "src", "wasm", "mathlib.wasm");
const outPath = join(root, "src", "wasm", "mathlib_bytes.ts");

const bytes = await readFile(wasmPath);
const hex = Array.from(bytes)
  .map((b) => "0x" + b.toString(16).padStart(2, "0"))
  .join(", ");

const header = [
  `// AUTO-GENERATED by scripts/gen_mathlib_bytes.ts — do not edit manually.`,
  `// Recompile: wasmtk convert src/wasm/mathlib.wat`,
  `// Regenerate: bun scripts/gen_mathlib_bytes.ts`,
  `// ${bytes.length} bytes`,
].join("\n");

const content = `${header}\nexport const MATHLIB_BYTES = new Uint8Array([${hex}]);\n`;

await writeFile(outPath, content);
console.log(`✅ Wrote ${bytes.length} bytes → ${outPath}`);
