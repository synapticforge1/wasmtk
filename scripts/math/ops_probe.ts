type i32 = number;
type f32 = number;
type f64 = number;
function main(): void {
  const big: i32 = 2147483647;
  const m: i32 = 65536;
  const neg: i32 = -1;
  const add: i32 = big + 1;
  const mul: i32 = m * m;
  const neg2: i32 = -(-2147483648);
  console.log("i32 overflow", add, mul, neg2);
  const seven: i32 = 7;
  const two: i32 = 2;
  const q: i32 = seven / two;
  const r: i32 = -7 % 2;
  console.log("i32 div/rem", q, r);
  const u: i32 = neg >>> 0;
  console.log("unsigned shift", neg >>> 0, u, neg >>> 1);
  const sh: i32 = 1 << 31;
  const sh2: i32 = 1 << 33;
  console.log("shift", sh, sh2, big << 1);
  const huge: f64 = 4294967298.7;
  const nan: f64 = NaN;
  const ti: i32 = huge | 0;
  const tn: i32 = nan | 0;
  console.log("to int32 via |0", ti, tn);
  const fa: f32 = 0.1;
  const fb: f32 = 0.2;
  const fs: f32 = fa + fb;
  console.log("f32", fa, fs, Math.fround(0.1) + Math.fround(0.2), Math.fround(Math.fround(0.1) + Math.fround(0.2)));
  const b1: bigint = 9223372036854775807n;
  const b2: bigint = b1 + 1n;
  console.log("i64 wrap", b2);
  const zero: i32 = 0;
  const one: i32 = 1;
  const dz: i32 = one / zero;
  console.log("div by zero", dz);
}
main();
