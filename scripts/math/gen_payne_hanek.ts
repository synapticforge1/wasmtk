/**
 * Generates the Payne–Hanek trig argument reduction of src/wasm/mathlib.wat (wasMath L3,
 * 2026-10-09): the bits of 2/π computed EXACTLY with BigInt, and the WAT that multiplies a huge
 * argument's 53-bit mantissa by the right 288-bit window of them in 32-bit-limb integer arithmetic.
 * The output replaces the region between the BEGIN / END markers in mathlib.wat.
 *
 * Why: the Cody–Waite reduction (`$__trig_reduce`) is exact only while n = round(x·2/π) is; from
 * |x| ≈ 1e15 it returned garbage (sin(1e18) = 5.98e27, sw61) and from ≈ 1.45e19 it trapped (ld28).
 *
 * Usage: bun scripts/math/gen_payne_hanek.ts
 */
import { readFile, writeFile } from "node:fs/promises";

const WAT = new URL("../../src/wasm/mathlib.wat", import.meta.url);
const CHUNKS = 48; // 32-bit chunks of 2/π after the binary point (1536 bits; the need is < 1300)
const T = 9; // chunks in the window: truncation error < 2^-202 of a unit (need 2^-166)

// ── 2/π to 1600 bits, exactly (Machin: π = 16·atan(1/5) − 4·atan(1/239)) ─────────────────────
const N = 1700n; // working fixed-point bits
const ONE = 1n << N;
const atanInv = (x: bigint): bigint => {
  let sum = 0n, term = ONE / x, k = 0n;
  const x2 = x * x;
  while (term !== 0n) {
    sum += (k % 2n === 0n ? term : -term) / (2n * k + 1n);
    term /= x2;
    k++;
  }
  return sum;
};
const piFix = 16n * atanInv(5n) - 4n * atanInv(239n); // π · 2^N
const twoOverPi = (2n << (2n * N)) / piFix; // (2/π) · 2^N
const chunk = (j: number): bigint => (twoOverPi >> (N - 32n * BigInt(j + 1))) & 0xffffffffn;
const chunks = Array.from({ length: CHUNKS }, (_, j) => chunk(j));
// Cross-check against the well-known leading digits (fdlibm's two_over_pi table).
if (chunks[0] !== 0xa2f9836en || chunks[1] !== 0x4e441529n || chunks[2] !== 0xfc2757d1n) {
  throw new Error(`2/π check failed: ${chunks.slice(0, 3).map((c) => c.toString(16)).join(" ")}`);
}

// ── The WAT ──────────────────────────────────────────────────────────────────────────────────
const lines: string[] = [];
const L = (s: string) => lines.push(s);
L(`  ;; ── BEGIN generated by scripts/math/gen_payne_hanek.ts: do not edit by hand ──`);
L(`  ;; $__twoopi(j): bits 32j+1 … 32j+32 of 2/π after the binary point (as an i64 in [0, 2^32)).`);
L(`  (func $__twoopi (param $j i32) (result i64)`);
for (let j = 0; j < CHUNKS; j++) L(`    (if (i32.eq (local.get $j) (i32.const ${j})) (then (return (i64.const 0x${chunks[j].toString(16)}))))`);
L(`    (i64.const 0))`);
const LIMBS = T + 2; // M = m · W < 2^53 · 2^(32T): T + 2 limbs of 32 bits
const lp = Array.from({ length: LIMBS }, (_, p) => `$L${p}`);
L(`  ;; $__ph_limb(k, L0 … L${LIMBS - 1}): limb k (0 below the range).`);
L(`  (func $__ph_limb (param $k i32) ${lp.map((l) => `(param ${l} i64)`).join(" ")} (result i64)`);
for (let p = 0; p < LIMBS; p++) L(`    (if (i32.eq (local.get $k) (i32.const ${p})) (then (return (local.get ${lp[p]}))))`);
L(`    (i64.const 0))`);
L(`  ;; Payne–Hanek: |x| (≥ 2^28, finite) → the dd remainder r of |x| − n·π/2 in $__tr / $__trt,`);
L(`  ;; |r| ≤ π/4 (to within the 2^-192 complement), and returns n & 3.`);
L(`  ;; |x| = m·2^q (m: 53 bits). x·2/π = m·2^q·Σ bᵢ2^-ⁱ; chunks before j0`);
L(`  ;; contribute multiples of 4 (dropped). M = m · (T chunks from j0) as ${LIMBS} limbs; its binary point`);
L(`  ;; is at bit P0 = 32T − S, S = q − 32·j0.`);
L(`  (func $__trig_reduce_ph (param $ax f64) (result i32)`);
L(`    (local $b i64) (local $q i32) (local $j0 i32) (local $S i32) (local $P0 i32) (local $A i32) (local $r i32)`);
L(`    (local $m i64) (local $mh i64) (local $ml i64) (local $c i64) (local $plo i64) (local $phi i64)`);
L(`    ${lp.map((l) => `(local ${l} i64)`).join(" ")}`);
L(`    (local $n i32) (local $neg i32) (local $flip i64) (local $msk i64) (local $fh f64) (local $fl f64) (local $t f64) (local $k i32)`);
L(`    (local.set $b (i64.reinterpret_f64 (local.get $ax)))`);
L(`    (local.set $q (i32.sub (i32.wrap_i64 (i64.shr_u (local.get $b) (i64.const 52))) (i32.const 1075)))`);
L(`    (local.set $m (i64.or (i64.and (local.get $b) (i64.const 0xfffffffffffff)) (i64.const 0x10000000000000)))`);
L(`    (local.set $mh (i64.shr_u (local.get $m) (i64.const 32)))`);
L(`    (local.set $ml (i64.and (local.get $m) (i64.const 0xffffffff)))`);
L(`    (local.set $j0 (select (i32.div_s (i32.sub (local.get $q) (i32.const 2)) (i32.const 32)) (i32.const 0) (i32.ge_s (local.get $q) (i32.const 2))))`);
L(`    (local.set $S (i32.sub (local.get $q) (i32.shl (local.get $j0) (i32.const 5))))`);
// Accumulate the partial products: chunk t has limb weight u = T−1−t.
for (let t = 0; t < T; t++) {
  const u = T - 1 - t;
  L(`    (local.set $c (call $__twoopi (i32.add (local.get $j0) (i32.const ${t}))))`);
  L(`    (local.set $plo (i64.mul (local.get $ml) (local.get $c)))`);
  L(`    (local.set $phi (i64.mul (local.get $mh) (local.get $c)))`);
  L(`    (local.set ${lp[u]} (i64.add (local.get ${lp[u]}) (i64.and (local.get $plo) (i64.const 0xffffffff))))`);
  L(`    (local.set ${lp[u + 1]} (i64.add (local.get ${lp[u + 1]}) (i64.add (i64.shr_u (local.get $plo) (i64.const 32)) (i64.and (local.get $phi) (i64.const 0xffffffff)))))`);
  L(`    (local.set ${lp[u + 2]} (i64.add (local.get ${lp[u + 2]}) (i64.shr_u (local.get $phi) (i64.const 32))))`);
}
// Carries.
for (let p = 0; p < LIMBS - 1; p++) {
  L(`    (local.set ${lp[p + 1]} (i64.add (local.get ${lp[p + 1]}) (i64.shr_u (local.get ${lp[p]}) (i64.const 32))))`);
  L(`    (local.set ${lp[p]} (i64.and (local.get ${lp[p]}) (i64.const 0xffffffff)))`);
}
const pick = (k: string) => `(call $__ph_limb ${k} ${lp.map((l) => `(local.get ${l})`).join(" ")})`;
L(`    (local.set $P0 (i32.sub (i32.const ${32 * T}) (local.get $S)))`);
L(`    (local.set $A (i32.shr_u (local.get $P0) (i32.const 5)))`);
L(`    (local.set $r (i32.and (local.get $P0) (i32.const 31)))`);
L(`    ;; n = the two integer bits just above the point`);
L(`    (local.set $n (i32.wrap_i64 (i64.and (i64.or`);
L(`      (i64.shr_u ${pick("(local.get $A)")} (i64.extend_i32_u (local.get $r)))`);
L(`      (i64.shl ${pick("(i32.add (local.get $A) (i32.const 1))")} (i64.extend_i32_u (i32.sub (i32.const 32) (local.get $r)))))`);
L(`      (i64.const 3))))`);
L(`    ;; centre the fraction f in [-1/2, 1/2] IN THE INTEGERS (a dd f − 1 would lose the low bits`);
L(`    ;; exactly when f ≈ 1): if its top bit (bit P0−1) is set, use 1 − f ≈ ~f (complemented bits;`);
L(`    ;; the missing 2^-(r+192) is far below the 2^-169 the hardest double needs), negated, n + 1.`);
L(`    (local.set $neg (i32.wrap_i64 (i64.and (i64.shr_u (i64.or`);
L(`      (i64.shl ${pick("(local.get $A)")} (i64.const 32))`);
L(`      ${pick("(i32.sub (local.get $A) (i32.const 1))")})`);
L(`      (i64.extend_i32_u (i32.add (local.get $r) (i32.const 31)))) (i64.const 1))))`);
L(`    (local.set $n (i32.add (local.get $n) (local.get $neg)))`);
L(`    (local.set $flip (select (i64.const 0xffffffff) (i64.const 0) (local.get $neg)))`);
L(`    ;; the fraction, as a sum of EXACT terms (a ≤ 32-bit integer times a power of two), in dd;`);
L(`    ;; all terms are ≥ 0 and occupy disjoint bits, so the dd sum keeps ~104 significant bits`);
L(`    (local.set $msk (i64.sub (i64.shl (i64.const 1) (i64.extend_i32_u (local.get $r))) (i64.const 1)))`);
L(`    (local.set $fh (call $__scalbn (f64.convert_i64_u (i64.and (i64.xor ${pick("(local.get $A)")} (local.get $flip)) (local.get $msk)))`);
L(`      (i32.sub (i32.const 0) (local.get $r))))`);
L(`    (local.set $fl (f64.const 0))`);
L(`    (local.set $k (i32.const 1))`);
L(`    (block $done (loop $next`);
L(`      (br_if $done (i32.gt_s (local.get $k) (i32.const 6)))`);
L(`      (local.set $t (call $__scalbn (f64.convert_i64_u (i64.xor ${pick("(i32.sub (local.get $A) (local.get $k))")} (local.get $flip)))`);
L(`        (i32.sub (i32.sub (i32.const 0) (local.get $r)) (i32.shl (local.get $k) (i32.const 5)))))`);
L(`      (call $__dda (local.get $fh) (local.get $fl) (local.get $t) (f64.const 0)) (local.set $fl) (local.set $fh)`);
L(`      (local.set $k (i32.add (local.get $k) (i32.const 1)))`);
L(`      (br $next)))`);
L(`    ;; r = ±fraction · π/2, in dd`);
L(`    (call $__ddm (local.get $fh) (local.get $fl)`);
L(`      (select (f64.const -1.5707963267948966) (f64.const 1.5707963267948966) (local.get $neg))`);
L(`      (select (f64.const -6.123233995736766e-17) (f64.const 6.123233995736766e-17) (local.get $neg)))`);
L(`    (call $__ts) (global.set $__trt) (global.set $__tr)`);
L(`    (i32.and (local.get $n) (i32.const 3)))`);
L(`  ;; ── END generated by scripts/math/gen_payne_hanek.ts ──`);

const src = await readFile(WAT, "utf8");
const begin = src.indexOf("  ;; ── BEGIN generated by scripts/math/gen_payne_hanek.ts");
const endMark = "  ;; ── END generated by scripts/math/gen_payne_hanek.ts ──";
const end = src.indexOf(endMark);
if (begin < 0 || end < 0) throw new Error("markers not found in mathlib.wat");
await writeFile(WAT, src.slice(0, begin) + lines.join("\n") + src.slice(end + endMark.length));
console.log(`wrote the Payne–Hanek region (${lines.length} lines; 2/π check passed)`);
