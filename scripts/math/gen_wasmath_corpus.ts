/**
 * Generates tests/wasi/wasm_wasi/39_WasMathAllFunctions.ts: every wasMath function called with up
 * to three representative inputs, in one program the ordinary wasi suite compiles, runs and
 * compares with Deno on every gate run.
 *
 * Inputs are chosen per parameter type and FILTERED through the TypeScript bodies: an input that
 * throws is left out (a throw ends a program; `39_WasMathStopsTheSame.ts` covers that), and so is a
 * u64 result ≥ 2⁶³ (wasm prints it signed: a known gap). Every `Math`-style member is included:
 * since L3 (2026-10-09) they run the same correctly rounded math library in Deno as in wasm.
 *
 * Usage: deno run -A scripts/math/gen_wasmath_corpus.ts
 */
import * as WM from "../../src/wasmath.ts";
import { WM_F32_TS, WM_F64_MATH, WM_WAT } from "../../src/wasmath_lower.ts";

type T = "i32" | "i64" | "f32" | "f64";
const OUT = "tests/wasi/wasm_wasi/39_WasMathAllFunctions.ts";

const ONE: Record<T, unknown[]> = {
  i32: [2147483647, -7, 0x55555555, 0, -2147483648],
  i64: [9223372036854775807n, -7n, 12345678901234567n, 0n, -(2n ** 63n)],
  f64: [2.5, -0, 0.1, -1e300, NaN, 4294967296.5, -3.5, 7],
  f32: [2.5, -0, 0.1, -1e30, NaN, 16777217, -3.5, 7].map((x) => Math.fround(x)),
};
const TWO: Record<T, unknown[][]> = {
  i32: [[2147483647, 1], [-7, 2], [0x55555555, 3], [-2147483648, -1], [5, 0], [12, 5]],
  i64: [[9223372036854775807n, 1n], [-7n, 2n], [12345678901234567n, 3n], [-(2n ** 63n), -1n], [5n, 0n], [12n, 5n]],
  f64: [[2.5, -0], [0.1, 3], [NaN, 1], [-1e300, 1e300], [-0, 0], [7, -2]],
  f32: [[2.5, -0], [0.1, 3], [NaN, 1], [-1e30, 1e30], [-0, 0], [7, -2]].map((p) => p.map((x) => Math.fround(x))),
};

const lit = (v: unknown, t: T): string => {
  if (t === "i64") return `${v}n`;
  const n = v as number;
  if (Number.isNaN(n)) return "NaN";
  if (n === Infinity) return "Infinity";
  if (n === -Infinity) return "-Infinity";
  if (Object.is(n, -0)) return "-0";
  return String(n);
};
const call = (ns: string, m: string, args: unknown[]) =>
  (WM as unknown as Record<string, Record<string, (...a: unknown[]) => unknown>>)[ns][m](...args);
const usable = (ns: string, m: string, args: unknown[]) => {
  try {
    const r = call(ns, m, args);
    return !((ns === "u64" || /toU64/.test(m)) && typeof r === "bigint" && r >= 2n ** 63n);
  } catch {
    return false;
  }
};

const lines: string[] = [
  "// Generated by scripts/math/gen_wasmath_corpus.ts: do not edit by hand. Every wasMath function",
  "// with up to three representative inputs; Deno runs the TypeScript bodies, wasm the lowering, and",
  "// the wasi suite requires the same output from both.",
  `import { f32, f64, i32, i64, u32, u64 } from "../../../src/wasmath.ts";`,
  "",
];
const sections: Record<string, string[]> = {};
const emit = (ns: string, m: string, params: T[]) => {
  const pool = params.length === 1 ? ONE[params[0]].map((v) => [v]) : TWO[params[0]];
  const picks = pool.filter((a) => usable(ns, m, a)).slice(0, 3);
  if (!picks.length) return;
  const calls = picks.map((a) => `${ns}.${m}(${a.map((v, j) => lit(v, params[Math.min(j, params.length - 1)])).join(", ")})`);
  (sections[ns] ??= []).push(`console.log("${ns}.${m}", ${calls.join(", ")});`);
};
for (const [key, h] of Object.entries(WM_WAT)) {
  if (key === "toint32") continue;
  const [ns, m] = [key.slice(0, 3), key.slice(4)];
  // the pair pools are typed by the FIRST param; mixed signatures use the single-value pools
  const params = h.params as T[];
  if (params.length === 2 && params[0] !== params[1]) continue;
  emit(ns, m, params);
}
for (const m of WM_F64_MATH) {
  if (/^[A-Z]/.test(m)) continue;
  emit("f64", m, ["atan2", "pow", "hypot"].includes(m) ? ["f64", "f64"] : ["f64"]);
}
for (const m of Object.keys(WM_F32_TS)) {
  emit("f32", m, ["atan2", "pow", "hypot"].includes(m) ? ["f64", "f64"] : ["f64"]);
}
for (const ns of ["i32", "u32", "i64", "u64", "f32", "f64"]) {
  if (!sections[ns]) continue;
  lines.push(`// ── ${ns} ──`, ...sections[ns], "");
}
await Deno.writeTextFile(OUT, lines.join("\n"));
console.log(`wrote ${OUT}: ${Object.values(sections).flat().length} functions`);
